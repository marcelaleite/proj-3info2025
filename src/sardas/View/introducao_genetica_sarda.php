          <h2>Sardas: um olhar genético sobre as manchinhas da pele</h2>
        </div>
        </CENTer>
        <section>
          <p>As sardas, também chamadas de efélides, são aquelas manchinhas marrons que aparecem principalmente em pessoas de pele clara, quase sempre no rosto, braços e ombros. Apesar de muita gente achar que elas aparecem “do nada” por causa do sol, a verdade é que o padrão de ter sardas já está escrito no DNA.</p>
          <br><center><h3>A genética por trás das sardas</h3></center><br>
          <p>O gene mais importante associado a essa característica é o <strong>MC1R</strong> (Melanocortin 1 Receptor), localizado no cromossomo 16. Esse gene controla o funcionamento de um receptor que fica na superfície das células da pele chamadas melanócitos — são essas células que produzem a melanina, o pigmento responsável por dar cor à pele, aos olhos e ao cabelo.</p>
          <p>Existem dois tipos principais de melanina:</p><br>
          <ul>
            <li><strong>Eumelanina</strong> → pigmento escuro, preto ou marrom; protege mais contra a radiação UV.</li>
            <li><strong>Feomelanina</strong> → pigmento claro, amarelado ou avermelhado; oferece menos proteção contra o sol.</li>
          </ul>
          <br><p>Quando o gene MC1R funciona de forma “completa”, a pele tende a produzir mais eumelanina, o que deixa a cor mais uniforme e protege melhor contra queimaduras solares. Mas algumas variações no gene MC1R alteram essa produção, levando o corpo a fabricar mais feomelanina. É nesse cenário que as sardas aparecem: a melanina não fica distribuída de forma homogênea na pele, mas concentrada em pequenas regiões, formando as manchas.</p><br>
          <center><h3>Dominância genética</h3></center><br>
          <p>O traço das sardas é considerado dominante. Isso significa que basta herdar um alelo (uma versão do gene) ligado às sardas de apenas um dos pais para que essa característica já possa se manifestar. Por exemplo:</p>
          <ul><br>
            <li><strong>AA</strong> (duas cópias do alelo) → pessoa certamente terá predisposição a sardas.</li>
            <li><strong>Aa</strong> (uma cópia só) → pessoa também terá predisposição.</li>
            <li><strong>aa</strong> (nenhum alelo) → pessoa sem predisposição genética a sardas.</li>
          </ul>
          <br><p>Ou seja, não é preciso “duas doses do gene”, como acontece em características recessivas (tipo olhos azuis).</p>
          <br><center><h3>Mas por que nem todos com o gene têm sardas iguais?</h3></center><br>
          <p>Aqui entra a influência ambiental. Mesmo quem tem o gene só desenvolve sardas visíveis com exposição ao sol. A radiação UV “ativa” os melanócitos, e como a produção de melanina não é homogênea nesses indivíduos, surgem as manchas em pontos concentrados. É por isso que muitas pessoas notam mais sardas no verão e veem elas clarearem ou sumirem no inverno.</p>
          <br><center><h3>Relação com outros fenótipos</h3></center><br>
          <p>As sardas aparecem com maior frequência em pessoas de pele clara e cabelos ruivos. Isso porque o mesmo gene MC1R também está relacionado à cor do cabelo. Indivíduos com mutações mais fortes nesse gene produzem pouquíssima eumelanina, resultando em cabelo ruivo, pele clara e alta sensibilidade ao sol.</p>
          <p>Mas atenção: ter sardas não significa automaticamente ser ruivo. Uma pessoa pode ter variantes mais “suaves” do MC1R que só resultam nas manchinhas, sem mudar drasticamente a cor do cabelo.</p>
